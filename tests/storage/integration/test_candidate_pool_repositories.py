def test_transition_runs_full_lifecycle(
    candidate_pool_run_repository: SqlAlchemyCandidatePoolRunRepository,
) -> None:
    """A run walks CALCULATED -> VALIDATED -> PUBLISHED end-to-end."""

    run = _new_calculated_run()
    candidate_pool_run_repository.add(run)

    validated = candidate_pool_run_repository.transition_status(
        run.id, CandidatePoolStatus.VALIDATED, at=_utc(2026, 7, 31, 10)
    )
    assert validated.status == CandidatePoolStatus.VALIDATED
    assert validated.finished_at == _utc(2026, 7, 31, 10)

    published = candidate_pool_run_repository.transition_status(
        run.id, CandidatePoolStatus.PUBLISHED, at=_utc(2026, 7, 31, 11)
    )
    assert published.status == CandidatePoolStatus.PUBLISHED
    assert published.published_at == _utc(2026, 7, 31, 11)


def test_transition_to_rejected_requires_reason(
    candidate_pool_run_repository: SqlAlchemyCandidatePoolRunRepository,
) -> None:
    """The repository surfaces the domain invariant via ValueError."""

    run = _new_calculated_run()
    candidate_pool_run_repository.add(run)
    candidate_pool_run_repository.transition_status(
        run.id, CandidatePoolStatus.VALIDATED, at=_utc(2026, 7, 31, 10)
    )

    with pytest.raises(ValueError):
        candidate_pool_run_repository.transition_status(
            run.id,
            CandidatePoolStatus.REJECTED,
            at=_utc(2026, 7, 31, 11),
        )

    rejected = candidate_pool_run_repository.transition_status(
        run.id,
        CandidatePoolStatus.REJECTED,
        at=_utc(2026, 7, 31, 11),
        rejection_reason="coverage below threshold",
    )
    assert rejected.status == CandidatePoolStatus.REJECTED
    assert rejected.rejection_reason == "coverage below threshold"
    assert rejected.rejected_at == _utc(2026, 7, 31, 11)


