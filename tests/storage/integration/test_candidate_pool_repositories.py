def _utc(year: int, month: int, day: int, hour: int = 0) -> datetime:
    return datetime(year, month, day, hour, tzinfo=UTC)


def _insert_instrument(db_session: Session, *, symbol: str) -> UUID:
    """Insert a minimal ``core.instruments`` row the items can reference.

    Returns the UUID generated by the database; the ``db_session``
    caller flushes the change so the row is visible to subsequent
    ``SELECT`` queries inside the same savepoint.
    """

    inserted = db_session.execute(
        text(
            "INSERT INTO core.instruments (id, symbol, exchange, name, "
            "instrument_type, currency, status, is_active, created_at, "
            "updated_at) VALUES (gen_random_uuid(), :symbol, 'SSE', :symbol, "
            "'ETF', 'CNY', 'active', true, now(), now()) RETURNING id"
        ),
        {"symbol": symbol},
    ).scalar_one()
    db_session.flush()
    return inserted


def _new_calculated_run(
    *,
    trade_date: date = date(2026, 7, 31),
    algorithm_key: str = "candidate_pool.v1",
    algorithm_version: str = "v1.0",
    parameter_set_key: str = "default",
    parameter_hash: str = "a" * 64,
    input_snapshot_id: UUID | None = None,
    input_row_count: int = 100,
    included_count: int = 10,
) -> CandidatePoolRun:
    return CandidatePoolRun(
        id=uuid4(),
        trade_date=trade_date,
        algorithm_key=algorithm_key,
        algorithm_version=algorithm_version,
        parameter_set_key=parameter_set_key,
        parameter_hash=parameter_hash,
        input_snapshot_id=input_snapshot_id or uuid4(),
        input_row_count=input_row_count,
        included_count=included_count,
        status=CandidatePoolStatus.CALCULATED,
        created_at=_utc(2026, 7, 31, 9),
    )


def test_add_persists_calculated_run(
    candidate_pool_run_repository: SqlAlchemyCandidatePoolRunRepository,
) -> None:
    """``add`` writes every column of the candidate-pool run row."""

    run = _new_calculated_run()

    persisted = candidate_pool_run_repository.add(
        run, quality_summary={"coverage": 0.97, "rule_errors": 0}
    )

    assert persisted.id == run.id
    assert persisted.status == CandidatePoolStatus.CALCULATED
    assert persisted.trade_date == run.trade_date
    assert persisted.algorithm_key == run.algorithm_key
    assert persisted.algorithm_version == run.algorithm_version
    assert persisted.parameter_set_key == run.parameter_set_key
    assert persisted.parameter_hash == run.parameter_hash
    assert persisted.input_snapshot_id == run.input_snapshot_id
    assert persisted.input_row_count == run.input_row_count
    assert persisted.included_count == run.included_count
    assert persisted.created_at == run.created_at

    fetched = candidate_pool_run_repository.get_by_id(run.id)
    assert fetched is not None
    assert fetched.id == run.id
    assert fetched.status == CandidatePoolStatus.CALCULATED


def test_duplicate_natural_key_raises_integrity_error(
    candidate_pool_run_repository: SqlAlchemyCandidatePoolRunRepository,
) -> None:
    """The ADR-0008 natural-key unique constraint rejects duplicates."""

    snapshot = uuid4()
    first = _new_calculated_run(
        trade_date=date(2026, 7, 31),
        algorithm_key="candidate_pool.v1",
        algorithm_version="v1.0",
        parameter_hash="a" * 64,
        input_snapshot_id=snapshot,
    )
    duplicate = _new_calculated_run(
        trade_date=date(2026, 7, 31),
        algorithm_key="candidate_pool.v1",
        algorithm_version="v1.0",
        parameter_hash="a" * 64,
        input_snapshot_id=snapshot,
    )

    candidate_pool_run_repository.add(first)
    with pytest.raises(IntegrityError):
        candidate_pool_run_repository.add(duplicate)


def test_get_by_natural_key_returns_persisted_run(
    candidate_pool_run_repository: SqlAlchemyCandidatePoolRunRepository,
) -> None:
    """``get_by_natural_key`` is the idempotent rerun lookup surface."""

    snapshot = uuid4()
    first = _new_calculated_run(
        trade_date=date(2026, 7, 31),
        algorithm_key="candidate_pool.v1",
        algorithm_version="v1.0",
        parameter_hash="a" * 64,
        input_snapshot_id=snapshot,
    )
    candidate_pool_run_repository.add(first)
    candidate_pool_run_repository.transition_status(
        first.id, CandidatePoolStatus.VALIDATED, at=_utc(2026, 7, 31, 10)
    )
    candidate_pool_run_repository.transition_status(
        first.id, CandidatePoolStatus.PUBLISHED, at=_utc(2026, 7, 31, 11)
    )

    fetched = candidate_pool_run_repository.get_by_natural_key(
        trade_date=date(2026, 7, 31),
        algorithm_key="candidate_pool.v1",
        algorithm_version="v1.0",
        parameter_hash="a" * 64,
        input_snapshot_id=snapshot,
    )

    assert fetched is not None
    assert fetched.id == first.id
    assert fetched.status == CandidatePoolStatus.PUBLISHED
    assert fetched.published_at == _utc(2026, 7, 31, 11)


