"""Integration tests for the candidate-pool storage repositories.

Each test runs inside the savepoint-isolated ``db_session`` fixture
defined in :mod:`tests.storage.integration.conftest`. The fixture spins
up a disposable PostgreSQL container via Testcontainers and rolls back
every change after the test, so the tests in this file can share a
single container without leaking data between cases.

The fixtures create the ``analytics.candidate_pool_runs`` and
``analytics.candidate_pool_items`` tables (along with the rest of the
PR-01 / PR-02 schema) directly through ``Base.metadata.create_all``.
The repositories only rely on the SQLAlchemy model so the migration
``20260731_0003`` is exercised on a real PostgreSQL deployment rather
than re-implemented in the fixture.
"""

